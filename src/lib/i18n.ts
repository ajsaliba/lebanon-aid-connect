const STORAGE_KEY = 'cedars-alert-lang';

function getStoredLang(): Language {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'ar' || stored === 'fr' || stored === 'en') return stored;
  } catch { /* SSR or no storage */ }
  return 'en';
}

let currentLang: Language = getStoredLang();
const listeners = new Set<() => void>();

export function setLanguage(lang: Language) {
  currentLang = lang;
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* ignore */ }
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.documentElement.lang = lang;
  listeners.forEach(fn => fn());
}

export function getLanguage(): Language { return currentLang; }

export function t(key: string): string {
  return translations[currentLang]?.[key] ?? translations.en[key] ?? key;
}

export function useTranslation() {
  const [, setTick] = useState(0);
  useEffect(() => {
    const listener = () => setTick(n => n + 1);
    listeners.add(listener);
    return () => { listeners.delete(listener); };
  }, []);
  const changeLanguage = useCallback((lang: Language) => setLanguage(lang), []);
  return { t, lang: currentLang, changeLanguage };
}

// Initialize direction on load
if (typeof document !== 'undefined') {
  document.documentElement.dir = currentLang === 'ar' ? 'rtl' : 'ltr';
  document.documentElement.lang = currentLang;
}
